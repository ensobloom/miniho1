<?php

mb_language("Japanese");
mb_internal_encoding("UTF-8");

// POST以外は禁止
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    header('Location: ./');
    exit;
}

// --------------------------------------------------
// スパム対策（honeypot）
// --------------------------------------------------
if (!empty($_POST['_gotcha'])) {
    header('Location: ./');
    exit;
}


// --------------------------------------------------
// 入力内容取得
// --------------------------------------------------
$name = trim($_POST['name'] ?? '');
$company = trim($_POST['company'] ?? '');
$email = trim($_POST['email'] ?? '');
$phone = trim($_POST['phone'] ?? '');
$inquiryType = trim($_POST['inquiry_type'] ?? '');
$message = trim($_POST['message'] ?? '');
$privacy = trim($_POST['privacy'] ?? '');


// --------------------------------------------------
// 必須項目チェック
// --------------------------------------------------
if (
    $name === '' ||
    $company === '' ||
    $email === '' ||
    $inquiryType === '' ||
    $message === '' ||
    $privacy === ''
) {
    exit('必須項目が入力されていません。');
}


// --------------------------------------------------
// メールアドレスチェック
// --------------------------------------------------
if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
    exit('メールアドレスの形式が正しくありません。');
}


// --------------------------------------------------
// 改行コードなどを除去
// ヘッダーインジェクション対策
// --------------------------------------------------
$name = str_replace(["\r", "\n"], '', $name);
$company = str_replace(["\r", "\n"], '', $company);
$email = str_replace(["\r", "\n"], '', $email);


// --------------------------------------------------
// 管理者通知先
// --------------------------------------------------
$adminEmails = [
    'nakanoya@bcinc.co.jp',
    'kaito.t1826@gmail.com'
];

$to = implode(',', $adminEmails);


// --------------------------------------------------
// 管理者向けメール
// --------------------------------------------------
$adminSubject = '【mendAI】サイトからお問い合わせがありました';

$adminBody = <<<EOT
mendAIサイトからお問い合わせがありました。

----------------------------------------
■ お名前
{$name}

■ 会社名・店舗名
{$company}

■ メールアドレス
{$email}

■ 電話番号
{$phone}

■ お問い合わせ種別
{$inquiryType}

■ お問い合わせ内容
{$message}
----------------------------------------

このメールはmendAIサイトのお問い合わせフォームから
自動送信されています。
EOT;


// --------------------------------------------------
// 送信元
//
// ↓ここは実際のサイトドメインのメールアドレスに
// 変更するのがおすすめです
// --------------------------------------------------
$fromEmail = 'noreply@bcinc.co.jp';

$adminHeaders = "From: mendAI <{$fromEmail}>\r\n";
$adminHeaders .= "Reply-To: {$email}\r\n";
$adminHeaders .= "Content-Type: text/plain; charset=UTF-8\r\n";


// --------------------------------------------------
// 管理者へ送信
// --------------------------------------------------
$adminResult = mb_send_mail(
    $to,
    $adminSubject,
    $adminBody,
    $adminHeaders
);


// --------------------------------------------------
// お客様への自動返信メール
// --------------------------------------------------
$userSubject = '【mendAI】お問い合わせありがとうございます';

$userBody = <<<EOT
{$name} 様

この度はmendAIへお問い合わせいただき、
誠にありがとうございます。

以下の内容でお問い合わせを受け付けました。

----------------------------------------
■ お名前
{$name}

■ 会社名・店舗名
{$company}

■ メールアドレス
{$email}

■ 電話番号
{$phone}

■ お問い合わせ種別
{$inquiryType}

■ お問い合わせ内容
{$message}
----------------------------------------

内容を確認のうえ、
担当者より通常2営業日以内にご連絡いたします。

何卒よろしくお願いいたします。

----------------------------------------
mendAI
合同会社B・C
----------------------------------------

※このメールは自動送信されています。
EOT;

$userHeaders = "From: mendAI <{$fromEmail}>\r\n";
$userHeaders .= "Reply-To: nakanoya@bcinc.co.jp\r\n";
$userHeaders .= "Content-Type: text/plain; charset=UTF-8\r\n";


// --------------------------------------------------
// 自動返信
// --------------------------------------------------
$userResult = mb_send_mail(
    $email,
    $userSubject,
    $userBody,
    $userHeaders
);


// --------------------------------------------------
// 送信結果
// --------------------------------------------------
if ($adminResult && $userResult) {

    // 送信完了後
    header('Location: ./thanks.html');
    exit;

} else {

    exit('メールの送信に失敗しました。時間をおいて再度お試しください。');

}